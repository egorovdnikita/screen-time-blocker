// APP-21: план локальных уведомлений (чистая функция, без браузера).
import fs from 'node:fs';import assert from 'node:assert/strict';import ts from 'typescript';
const source=fs.readFileSync(new URL('../src/data/notificationPlan.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exports={};new Function('exports',code)(exports);const {plannedNotifications,shifted}=exports;
const prefs={diary:false,sessionStart:true,sessionEnd:true,unlockWarning:true,unlockEnd:true,allOff:false};
const now=Date.UTC(2026,10,3,12);
const work={id:'w',title:'Работа',schedule:{kind:'weekly',start:540,end:1020,days:[0,4]}};
const night={id:'n',title:'Ночь',schedule:{kind:'weekly',start:1380,end:420,days:[6]}};
const base={notifications:prefs,sessions:[work],titles:{},paused:{},unlocks:{},unlockNames:{},now};
let plan=plannedNotifications(base);
assert.deepEqual(plan.map(x=>x.id),['block-start-w-0','block-end-w-0','block-start-w-4','block-end-w-4']);
assert.deepEqual(plan[0].trigger,{kind:'weekly',weekday:2,hour:8,minute:55},'пн 8:55, expo weekday 2 = понедельник');
assert.deepEqual(plan[3].trigger,{kind:'weekly',weekday:6,hour:16,minute:55},'пт 16:55');
plan=plannedNotifications({...base,sessions:[night]});
assert.deepEqual(plan[0].trigger,{kind:'weekly',weekday:1,hour:22,minute:55},'вс 22:55');
assert.deepEqual(plan[1].trigger,{kind:'weekly',weekday:2,hour:6,minute:55},'конец через полночь — пн 6:55');
assert.deepEqual(shifted(0,2,5),{weekday:1,hour:23,minute:57},'0:02 пн минус 5 мин — вс 23:57');
assert.equal(plannedNotifications({...base,notifications:{...prefs,allOff:true}}).length,0,'Общее отключение');
assert.equal(plannedNotifications({...base,paused:{w:'manual'}}).length,0,'Пауза снимает уведомления');
assert.equal(plannedNotifications({...base,titles:{w:'Фокус'}})[0].title,'Фокус','Переименование');
const onlyEnd=plannedNotifications({...base,notifications:{...prefs,sessionStart:false}});assert.ok(onlyEnd.every(x=>x.id.startsWith('block-end')));
const nowSession={id:'s',title:'Сессия',schedule:{kind:'now',startedAt:now-10*60000,minutes:30}};
plan=plannedNotifications({...base,sessions:[nowSession]});assert.deepEqual(plan.map(x=>[x.id,x.trigger.at]),[['block-end-s',now+15*60000]]);
assert.equal(plannedNotifications({...base,sessions:[{...nowSession,schedule:{kind:'now',startedAt:now-28*60000,minutes:30}}]}).length,0,'Поздно предупреждать');
plan=plannedNotifications({...base,sessions:[],unlocks:{l:{until:now+5*60000}},unlockNames:{l:'Instagram'}});
assert.deepEqual(plan.map(x=>[x.id,x.title,x.trigger.at]),[['block-unlock-warn-l','Instagram',now+4*60000],['block-unlock-end-l','Instagram',now+5*60000]]);
assert.equal(plannedNotifications({...base,sessions:[],unlocks:{l:{until:now-1}}}).length,0,'Истёкший доступ');
plan=plannedNotifications({...base,sessions:[],notifications:{...prefs,diary:true}});assert.deepEqual(plan[0].trigger,{kind:'daily',hour:20,minute:0});
console.log('Notification plan OK');
